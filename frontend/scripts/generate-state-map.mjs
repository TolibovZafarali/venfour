import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

// Preprojected Census boundaries keep mapping libraries out of the browser bundle.
const source = "https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/states-albers-10m.json";
const raw = process.argv[2]
  ? await readFile(process.argv[2], "utf8")
  : await fetch(source).then(response => {
    if (!response.ok) throw new Error(`Map download failed: ${response.status}`);
    return response.text();
  });
const topology = JSON.parse(raw);
const { jurisdictions } = JSON.parse(await readFile(new URL("../../venfour/data/nationwide_product_v1.json", import.meta.url), "utf8"));
const arcs = topology.arcs.map(arc => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * topology.transform.scale[0] + topology.transform.translate[0], y * topology.transform.scale[1] + topology.transform.translate[1]];
  });
});
const ringPath = ring => {
  const points = ring.flatMap((index, position) => {
    const points = index < 0 ? [...arcs[~index]].reverse() : arcs[index];
    return position ? points.slice(1) : points;
  });
  return points.map(([x, y], index) => `${index ? "L" : "M"}${x.toFixed(1)},${y.toFixed(1)}`).join("") + "Z";
};
const paths = Object.fromEntries(jurisdictions.map(({ name, code }) => {
  const geometry = topology.objects.states.geometries.find(item => item.properties.name === name);
  if (!geometry) throw new Error(`Missing state geometry: ${name}`);
  const polygons = geometry.type === "Polygon" ? [geometry.arcs] : geometry.arcs;
  return [code, polygons.flatMap(polygon => polygon.map(ringPath)).join("")];
}));
const license = await readFile(new URL("../public/assets/us-atlas-LICENSE.txt", import.meta.url), "utf8");
const header = `// Generated by frontend/scripts/generate-state-map.mjs. Do not edit by hand.
// Source: ${source}
// SHA-256: ${createHash("sha256").update(raw).digest("hex")}
// 2017 Census cartographic boundaries; Albers USA projection, Alaska/Hawaii insets.
// us-atlas ISC license: frontend/public/assets/us-atlas-LICENSE.txt
/*! ${license.trim()} */
`;
await writeFile(new URL("../src/features/states/map-paths.ts", import.meta.url), `${header}export const stateMapPaths: Record<string, string> = ${JSON.stringify(paths, null, 2)};\n`);
console.log(`Generated ${Object.keys(paths).length} state paths.`);
