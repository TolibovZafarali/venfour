const supportedConditionalSchemaDigest =
  "dccb7d97a6d1d355e2268fd71186e3db7c3782f5230111fb0735916b7b0bbcec";

function collectConditionalConstraints(value, currentPath = "$", result = []) {
  if (Array.isArray(value)) {
    value.forEach((child, index) =>
      collectConditionalConstraints(child, `${currentPath}[${index}]`, result),
    );
    return result;
  }

  if (!value || typeof value !== "object") {
    return result;
  }

  for (const [key, child] of Object.entries(value)) {
    if (key === "allOf" && Array.isArray(child)) {
      child.forEach((branch, index) => {
        if (branch && typeof branch === "object" && "if" in branch) {
          result.push({
            path: `${currentPath}.allOf[${index}]`,
            branch,
          });
        }
      });
    }
    collectConditionalConstraints(child, `${currentPath}.${key}`, result);
  }

  return result;
}

function synchronizeNullablePair(definition, valueKey, displayKey) {
  const { allOf: _conditionalBranches, ...structuralDefinition } = definition;
  const valueProperty = definition.properties[valueKey];
  const displayProperty = definition.properties[displayKey];

  return {
    oneOf: [
      {
        ...structuralDefinition,
        properties: {
          ...definition.properties,
          [valueKey]: { type: "null" },
          [displayKey]: { type: "null" },
        },
      },
      {
        ...structuralDefinition,
        properties: {
          ...definition.properties,
          [valueKey]: {
            ...valueProperty,
            type: valueProperty.type.find((type) => type !== "null"),
          },
          [displayKey]: {
            ...displayProperty,
            type: displayProperty.type.find((type) => type !== "null"),
          },
        },
      },
    ],
  };
}

// The compiler turns JSON Schema conditionals into open index signatures.
// Remove those branches from its structural pass, then restore the schema's
// cross-field relationships with the discriminated refinements appended below.
function removeConditionalConstraints(value) {
  if (Array.isArray(value)) {
    return value.map(removeConditionalConstraints);
  }

  if (!value || typeof value !== "object") {
    return value;
  }

  const result = {};
  for (const [key, child] of Object.entries(value)) {
    if (key === "allOf" && Array.isArray(child)) {
      const structuralBranches = child.filter(
        (branch) =>
          !branch || typeof branch !== "object" || !("if" in branch),
      );
      if (structuralBranches.length > 0) {
        result[key] = structuralBranches.map(removeConditionalConstraints);
      }
      continue;
    }

    result[key] = removeConditionalConstraints(child);
  }
  return result;
}

const source = await readFile(schemaPath, "utf8");
const sourceDigest = createHash("sha256").update(source).digest("hex");
const parsedSchema = JSON.parse(source);
const conditionalSchemaDigest = createHash("sha256")
  .update(JSON.stringify(collectConditionalConstraints(parsedSchema)))
  .digest("hex");

if (conditionalSchemaDigest !== supportedConditionalSchemaDigest) {
  throw new Error(
    "The analysis schema's conditional constraints changed. Review and update the generated contract refinements before regenerating.",
  );
}

parsedSchema.$defs.money = synchronizeNullablePair(
  parsedSchema.$defs.money,
  "cents",
  "display",
);
parsedSchema.$defs.basisPointValue = synchronizeNullablePair(
  parsedSchema.$defs.basisPointValue,
  "basisPoints",
  "display",
);

const schema = removeConditionalConstraints(parsedSchema);
schema.title = "AnalysisPresentationBase";

const structuralContract = await compile(schema, "AnalysisPresentationBase", {
  additionalProperties: false,
  bannerComment: `/**
 * Generated from schemas/analysis/analysis-presentation.schema.json.
 * Source schema SHA-256: ${sourceDigest}.
 * Run \`npm run generate:contracts\` after changing the backend schema.
 * Do not edit this file directly.
 */`,
  cwd: path.dirname(schemaPath),
  unknownAny: true,
});

